def decode_row(code):
    row = []
    for m in re.finditer(r'([A-Z])(\d+)', code):
        sym, count = m.group(1), int(m.group(2))
        row.extend([SYMBOLS.get(sym, sym)] * count)
    return row

def print_level(code):
    rows = code.split('|')
    for r in rows:
        print(''.join(decode_row(r)))
    print(f"rows: {len(rows)}, widths: {[len(decode_row(r)) for r in rows]}")

if __name__ == '__main__':
    import sys
    if len(sys.argv) > 1:
        for name in sys.argv[1:]:
            if name in LEVELS:
                print(f"=== {name} ===")
                print_level(LEVELS[name])
            else:
                print(f"Unknown level: {name}")
    else:
        for name, code in LEVELS.items():
            print(f"=== {name} ===")
            print_level(code)
            print()
